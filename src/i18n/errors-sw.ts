/** The message in the reader's language: Swahili when there's one, otherwise the English as thrown. */
export function localizeError(message: string, locale: string | null | undefined): string {
  if (!locale || !locale.toLowerCase().startsWith("sw")) return message;
  const exact = SW_ERRORS[message];
  if (exact) return exact;
  for (const [re, to] of SW_PATTERNS) {
    const m = message.match(re);
    if (m) return to(...m.slice(1));
  }
  return message;
}
