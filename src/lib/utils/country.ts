export function getCountryFlag(name: string): string | null {
    if (!name) return null
    // Normalize to title case for lookup (handles ALL CAPS names from DB)
    const titleCase = name.trim().toLowerCase().replace(/\b\w/g, c => c.toUpperCase())
    return countryFlags[titleCase] || countryFlags[name] || countryFlags[name.split(' ')[0]] || null
}
